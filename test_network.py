"""
Jovian Proxy Live Egress Integration Test Runner.

Validates outbound data scrubbing alongside inbound context token restoration
over active network sockets.
"""

import json
import os
import sys
import requests

os.environ['no_proxy'] = '127.0.0.1,localhost,0.0.0.0'

SERVER_TARGET_HOST = "127.0.0.1:8000"
chat_url = f"http://{SERVER_TARGET_HOST}/v1/proxy/chat"
restore_url = f"http://{SERVER_TARGET_HOST}/v1/proxy/restore"

headers = {
    "X-Gateway-API-Key": "sec_gateway_secret_abc123",
    "X-User-ID": "dev_network_auditor",
    "X-Department": "Cyber_Defense_Squad",
    "Content-Type": "application/json"
}

outbound_payload = {
    "prompt": "ALERT: Master deployment key is locked. Please check AWS credential AKIAIOSFODNN7EXAMPLE immediately."
}

print("🌐 [PHASE 1]: Dispatching outbound prompt packet to /v1/proxy/chat...")

try:
    # 1. Test the Outbound Scrubbing Route
    chat_response = requests.post(chat_url, json=outbound_payload, headers=headers, timeout=5)
    
    if chat_response.status_code != 200:
        print(f"❌ Chat Proxy Failed with status code: {chat_response.status_code}")
        print(chat_response.text)
        sys.exit(1)
        
    chat_data = chat_response.json()
    sanitized_text = chat_data.get("sanitized_prompt", "")
    print("🟢 [CHAT SUCCESS]: Outbound prompt successfully tokenized.")
    print(json.dumps(chat_data, indent=2))
    
    # ⚙️ FIXED TOKEN EXTRACTION LAYER: Automatically find the actual generated token placeholder anywhere in the prompt string
    import re
    token_match = re.search(r'USER_TOKEN_[A-Z0-9_]+', sanitized_text)
    extracted_token = token_match.group(0) if token_match else "USER_TOKEN_CLOUD_CREDENTIAL_1"
    
    # Extract the token placeholder generated by the vault (e.g., USER_TOKEN_CLOUD_CREDENTIAL_1)
    # We will simulate an incoming AI response referencing this exact token
    mock_ai_response = f"Processed request. Applied access updates directly to structural token profile: {extracted_token}."
    
    print(f"\n🤖 [PHASE 2]: Simulating inbound AI response containing placeholders:")
    print(f"   \"{mock_ai_response}\"")
    
    # 2. Test the Inbound Restoration Route
    print(f"\n🌐 [PHASE 3]: Shipping AI text block to /v1/proxy/restore...")
    restore_payload = {"text": mock_ai_response}
    
    restore_response = requests.post(restore_url, json=restore_payload, headers=headers, timeout=5)
    
    if restore_response.status_code == 200:
        print("🟢 [RESTORE SUCCESS]: System successfully unmasked proxy tokens natively.")
        print(json.dumps(restore_response.json(), indent=2))
        sys.exit(0)
    else:
        print(f"⚠️ [SERVER ALERT]: Restore endpoint returned status code {restore_response.status_code}")
        print(restore_response.text)
        sys.exit(1)

except requests.exceptions.ConnectionError as e:
    print(f"\n❌ Connection Failed. Target host '{SERVER_TARGET_HOST}' is unreachable. Ensure your uvicorn proxy server is running.")
    sys.exit(1)
